    fn init_elf_is_x86_64() {
        // e_machine at offset 18
        let machine = u16::from_le_bytes([INIT_ELF[18], INIT_ELF[19]]);
        assert_eq!(machine, 0x3E);
    }

    #[test]
    fn init_elf_has_pt_load_segment() {
        // p_type of first program header at offset 64
        let ptype = u32::from_le_bytes([
            INIT_ELF[64], INIT_ELF[65], INIT_ELF[66], INIT_ELF[67],
        ]);
        assert_eq!(ptype, 1); // PT_LOAD
    }
